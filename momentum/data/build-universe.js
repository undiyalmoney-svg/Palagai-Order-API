function hash(s) {
  let h = 2166136261;
  for (let i = 0; i < s.length; i += 1) h = Math.imul(h ^ s.charCodeAt(i), 16777619);
  return h >>> 0;
}

function priceFor(symbol, sector, hint) {
  if (hint) return hint;
  const n = hash(symbol) % 1000;
  const band = {
    BANK: 80 + n * 0.6, FINANCE: 90 + n, IT: 200 + n * 2, AUTO: 150 + n * 3,
    PHARMA: 180 + n * 2, FMCG: 120 + n, ENERGY: 60 + n * 0.4, METALS: 70 + n * 0.5,
    CONSUMER: 150 + n, CEMENT: 200 + n * 2, REALTY: 120 + n, CHEMICALS: 180 + n,
    DEFENCE: 250 + n * 2, TELECOM: 40 + n * 0.3, MEDIA: 80 + n * 0.4,
  };
  return Math.max(12, Math.round(band[sector] || 80 + n));
}

function collect() {
  const seen = new Set(CORE);
  const out = [];
  for (const [symbol, name, sector, px] of NAMED) {
    if (seen.has(symbol) || !/^[A-Z0-9&-]{2,20}$/.test(symbol)) continue;
    seen.add(symbol);
    out.push({ symbol, name, sector, basePrice: priceFor(symbol, sector, px), listed: LISTED });
  }
  let i = 1;
  while (out.length < 1000) {
    const sector = SECTORS[i % SECTORS.length];
    const symbol = `${PREFIX[sector]}${String(i).padStart(3, '0')}`;
    if (!seen.has(symbol)) {
      seen.add(symbol);
      out.push({
        symbol,
        name: `${NAMES[sector]} ${i}`,
        sector,
        basePrice: priceFor(symbol, sector),
        listed: LISTED,
      });
    }
    i += 1;
    if (i > 5000) break;
  }
  return out;
}

function emit(rows) {
  const lines = [
    "'use strict';",
    '',
    '/**',
    ' * Extended NSE-style cash universe. Core large-caps live in universe.js;',
    ' * these names are scanned live and in recent paper windows. `listed` keeps',
    ' * 2018–mid-2024 backtests on the original 50 so historical tests stay fast.',
    ' */',
    'const EXTENDED_UNIVERSE = [',
  ];
  for (const r of rows) {
    lines.push(
      `  { symbol: ${JSON.stringify(r.symbol)}, name: ${JSON.stringify(r.name)}, sector: ${JSON.stringify(r.sector)}, basePrice: ${r.basePrice}, listed: ${JSON.stringify(r.listed)} },`,
    );
  }
  lines.push('];');
  lines.push('');
  lines.push('module.exports = { EXTENDED_UNIVERSE };');
  lines.push('');
  const dest = path.join(__dirname, 'universe-extended.js');
  fs.writeFileSync(dest, lines.join('\n'));
  process.stdout.write(`wrote ${rows.length} names to ${dest}\n`);
}

